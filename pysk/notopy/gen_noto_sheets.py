#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_noto_sheets.py  (part 2 of 2)

Reads CSVs from pffsheets/noto_data/ (generated by extract_noto_data.py)
and builds pffsheets/noto_glyph_sheets.xlsx with 10 sheets.

run with regular Python (NOT fontforge):
  python3 pysk/notopy/gen_noto_sheets.py

requires: openpyxl  (pip install openpyxl)
"""

import csv
import sys
from pathlib import Path

try:
    import openpyxl
    from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
except ImportError:
    sys.exit("ERROR: pip install openpyxl")

pff_root = Path(__file__).resolve().parents[2]
CSV_DIR  = pff_root / "pffsheets/noto_data"
OUT_XLSX = pff_root / "pffsheets/noto_glyph_sheets.xlsx"

SCRIPTS_ORDER = [
    "xh38","xb38","xp38","xg38","xo38",
    "xt38","xj38","xk38","xm38","xs38",
]

HEADERS    = ["hex","nameslist","hskii","width","has_glyph","in_json"]
COL_WIDTHS = [8,    22,         8,      7,      10,          9]

HEADER_FILL  = PatternFill("solid", fgColor="1F497D")
HEADER_FONT  = Font(bold=True, color="FFFFFF", name="Consolas", size=10)
HAS_FILL     = PatternFill("solid", fgColor="E2EFDA")   # green: has glyph
CLEAR_FILL   = PatternFill("solid", fgColor="FCE4D6")   # orange: clear/empty
MISMATCH_FILL= PatternFill("solid", fgColor="FFF2CC")   # yellow: hskii != in_json
DATA_FONT    = Font(name="Consolas", size=9)
CENTER       = Alignment(horizontal="center")


def build_sheet(ws, csv_path, prefix):
    ws.title = prefix

    # freeze header + set column widths
    for c, (h, w) in enumerate(zip(HEADERS, COL_WIDTHS), 1):
        cell = ws.cell(row=1, column=c, value=h)
        cell.font      = HEADER_FONT
        cell.fill      = HEADER_FILL
        cell.alignment = CENTER
        ws.column_dimensions[cell.column_letter].width = w
    ws.freeze_panes = "A2"
    ws.row_dimensions[1].height = 16

    row_num = 2
    with open(csv_path, newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for rec in reader:
            has_g    = rec["has_glyph"] == "Y"
            hskii    = rec["hskii"]
            in_json  = rec["in_json"]
            mismatch = (hskii != in_json)

            if mismatch:
                fill = MISMATCH_FILL
            elif has_g:
                fill = HAS_FILL
            else:
                fill = CLEAR_FILL

            vals = [rec["hex"], rec["nameslist"], hskii,
                    int(rec["width"]), rec["has_glyph"], in_json]

            for c, v in enumerate(vals, 1):
                cell = ws.cell(row=row_num, column=c, value=v)
                cell.font = DATA_FONT
                cell.fill = fill
                if c in (1, 3, 5, 6):
                    cell.alignment = CENTER

            row_num += 1

    return row_num - 2


def main():
    if not CSV_DIR.exists():
        sys.exit(f"CSV dir not found: {CSV_DIR}\nRun: fontforge -script pysk/notopy/extract_noto_data.py")

    wb = openpyxl.Workbook()
    wb.remove(wb.active)   # remove default sheet

    total = 0
    for prefix in SCRIPTS_ORDER:
        csv_path = CSV_DIR / f"{prefix}.csv"
        if not csv_path.exists():
            print(f"  SKIP {prefix} (csv not found)")
            continue
        ws = wb.create_sheet()
        count = build_sheet(ws, csv_path, prefix)
        print(f"  {prefix}: {count} rows")
        total += count

    OUT_XLSX.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(OUT_XLSX))
    print(f"\nSaved: {OUT_XLSX}  ({total} total rows)")
    print("\nColor legend:")
    print("  green  = glyph exists in NotoSans")
    print("  orange = no glyph (clear/empty)")
    print("  yellow = hskii vs in_json mismatch (needs NamesList fix)")


if __name__ == "__main__":
    main()
