#!/usr/bin/env fontforge
# -*- coding: utf-8 -*-
"""
noto_to_xi38.py

Copy glyphs from NotoSans*.ttf fonts into notosfd/xi38/*asc.sfd files.

Uses notofonts/notottf-x38ascsfd.csv to know:
  - which ASCII slot in each xi38asc SFD to fill
  - which Unicode codepoint in each NotoSans TTF to copy from

CSV format (generated by gen_notottf_csv.py):
  ascii,xh38,xb38,xp38,xg38,xo38,xt38,xj38,xk38,xm38,xs38
  [ignore chars...],ignore,...
  A,0905,0985,0A01,0A85,...
  k,0915,0995,...

run:
  fontforge -script pysk/xi52py/noto_to_xi38.py
  or with filter:
    fontforge -script pysk/xi52py/noto_to_xi38.py xh38 xb38
"""

import fontforge
import csv
import sys
import logging
from pathlib import Path
from datetime import datetime

pff_root = Path(__file__).resolve().parents[2]

CSV_PATH  = pff_root / "notofonts/notottf-x38ascsfd.csv"
NOTO_DIR  = pff_root / "notofonts"
SFD_DIR   = pff_root / "notosfd/xi38"
LOG_DIR   = pff_root / "logs"
LOG_FILE  = LOG_DIR / "noto_to_xi38.log"

LOG_DIR.mkdir(parents=True, exist_ok=True)
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s  %(message)s",
    handlers=[
        logging.FileHandler(LOG_FILE, encoding="utf-8"),
        logging.StreamHandler(sys.stdout),
    ],
)
log = logging.getLogger(__name__)

# font prefix -> (NotoSans TTF filename, target SFD filename)
FONT_MAP = {
    "xh38": ("NotoSansDevanagari-Regular.ttf",  "xh38asc.sfd"),
    "xb38": ("NotoSansBengali-Regular.ttf",      "xb38asc.sfd"),
    "xp38": ("NotoSansGurmukhi-Regular.ttf",     "xp38asc.sfd"),
    "xg38": ("NotoSansGujarati-Regular.ttf",     "xg38asc.sfd"),
    "xo38": ("NotoSansOriya-Regular.ttf",        "xo38asc.sfd"),
    "xt38": ("NotoSansTamil-Regular.ttf",        "xt38asc.sfd"),
    "xj38": ("NotoSansTelugu-Regular.ttf",       "xj38asc.sfd"),
    "xk38": ("NotoSansKannada-Regular.ttf",      "xk38asc.sfd"),
    "xm38": ("NotoSansMalayalam-Regular.ttf",    "xm38asc.sfd"),
    "xs38": ("NotoSansSinhala-Regular.ttf",      "xs38asc.sfd"),
}


def read_csv(path):
    """
    Parse CSV and return:
      font_cols : list of font prefix strings  e.g. ['xh38','xb38',...]
      glyph_rows: list of (ascii_char, {font_prefix: unicode_int})

    Skips lines starting with '#' (comments) and the [ignore...] row.
    Cell value 'ignore' or empty = skip that glyph for that font.
    """
    font_cols  = []
    glyph_rows = []
    with open(path, encoding="utf-8", newline="") as f:
        reader = csv.reader(f)

        # skip comment lines, find actual header row
        header = None
        for row in reader:
            if not row or row[0].strip().startswith("#"):
                continue
            header = [c.strip() for c in row]
            break
        if not header:
            raise ValueError(f"no header row found in {path}")
        font_cols = header[1:]          # ['xh38', 'xb38', ...]

        # skip [ignore...] row
        for row in reader:
            if not row or row[0].strip().startswith("#"):
                continue
            break                       # consumed the ignore row

        # data rows
        for row in reader:
            if not row or not row[0].strip() or row[0].strip().startswith("#"):
                continue
            ascii_char = row[0].strip()
            col_map = {}
            for i, font in enumerate(font_cols):
                cell = row[i + 1].strip() if i + 1 < len(row) else ""
                if cell and cell.lower() not in ("", "ignore"):
                    try:
                        col_map[font] = int(cell, 16)
                    except ValueError:
                        log.warning(f"bad hex '{cell}' for char '{ascii_char}' col '{font}'")
            glyph_rows.append((ascii_char, col_map))
    return font_cols, glyph_rows


def process_font(font_prefix, glyph_rows):
    """Copy glyphs for one font. Returns (copied, skipped, failed)."""
    ttf_name, sfd_name = FONT_MAP[font_prefix]
    ttf_path = NOTO_DIR / ttf_name
    sfd_path = SFD_DIR  / sfd_name

    if not ttf_path.exists():
        log.error(f"[{font_prefix}] TTF not found: {ttf_path}")
        return 0, 0, 0
    if not sfd_path.exists():
        log.error(f"[{font_prefix}] SFD not found: {sfd_path}")
        return 0, 0, 0

    log.info(f"[{font_prefix}] opening {ttf_name}")
    src = fontforge.open(str(ttf_path))
    log.info(f"[{font_prefix}] opening {sfd_name}")
    dst = fontforge.open(str(sfd_path))

    copied = skipped = failed = 0

    for ascii_char, col_map in glyph_rows:
        if font_prefix not in col_map:
            skipped += 1
            continue

        src_cp  = col_map[font_prefix]          # Unicode in NotoSans
        dst_cp  = ord(ascii_char)               # ASCII slot in xi38asc

        try:
            # verify source glyph exists and has contours
            src_glyph = src[src_cp]
            if src_glyph.isWorthOutputting():
                src.selection.select(src_cp)
                src.copy()
                dst.selection.select(dst_cp)
                dst.paste()
                # copy width too
                dst[dst_cp].width = src_glyph.width
                copied += 1
                log.debug(f"  '{ascii_char}' <- U+{src_cp:04X}  w={src_glyph.width}")
            else:
                log.warning(f"  '{ascii_char}' U+{src_cp:04X}: empty glyph in {ttf_name}, skipped")
                skipped += 1
        except Exception as e:
            log.warning(f"  '{ascii_char}' U+{src_cp:04X}: {e}")
            failed += 1

    dst.save(str(sfd_path))
    log.info(f"[{font_prefix}] saved {sfd_name}  copied={copied} skipped={skipped} failed={failed}")
    src.close()
    dst.close()
    return copied, skipped, failed


def main():
    log.info("=" * 60)
    log.info(f"noto_to_xi38  started {datetime.now()}")

    if not CSV_PATH.exists():
        log.error(f"CSV not found: {CSV_PATH}")
        log.error("run gen_notottf_csv.py first")
        sys.exit(1)

    font_cols, glyph_rows = read_csv(CSV_PATH)
    log.info(f"CSV: {len(glyph_rows)} glyph rows, fonts: {font_cols}")

    # optional CLI filter: fontforge -script noto_to_xi38.py xh38 xb38
    wanted = set(sys.argv[1:]) if len(sys.argv) > 1 else set(FONT_MAP.keys())

    total_copied = total_failed = 0
    for prefix in font_cols:
        if prefix not in wanted:
            continue
        if prefix not in FONT_MAP:
            log.warning(f"no FONT_MAP entry for '{prefix}', skipping")
            continue
        c, s, f = process_font(prefix, glyph_rows)
        total_copied += c
        total_failed += f

    log.info("=" * 60)
    log.info(f"done  total copied={total_copied}  failed={total_failed}")
    log.info(f"log: {LOG_FILE}")
    print(f"\nDone! Logs: {LOG_FILE}")

    if total_failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
